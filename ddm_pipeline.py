def summarize(keys):
    beh, fits = [], []
    for key in keys:
        try:
            d = data_for(key)
        except Exception as e:
            print(f'skip {key}: {e}'); continue
        lab = SUBJECTS[key]['label']
        for cond in CONDS:
            g = d[d['block_type'] == cond]
            nz = g[g['coherence'] != 0]
            kn = int(((nz['response'] == 'high') == (nz['coherence'] > 0)).sum())
            nr = g[g['realized_coh'] != 0]
            kr = int(((nr['response'] == 'high') == (nr['realized_coh'] > 0)).sum())
            beh.append(dict(subject=lab, condition=cond, n=len(g),
                            acc_nominal=kn / len(nz), p_chance=binomtest(kn, len(nz), .5).pvalue,
                            acc_realized=kr / len(nr), n_realized_zero=int((g['realized_coh'] == 0).sum()),
                            rt_q01=g['rt'].quantile(.01), rt_med=g['rt'].median(),
                            rt_q90=g['rt'].quantile(.9), frac_before_end=(g['rt'] < STIM_DUR).mean()))
            for m in MODELS:
                fit = load_fit(key, cond, m)
                if fit is None:
                    print('missing fit:', os.path.basename(fit_path(key, cond, m))); continue
                p, pinned = params_of(fit)
                fits.append(dict(subject=lab, condition=cond, model=m,
                                 **fit_stats(fit, len(g)), **p, pinned=pinned))
        r, i = [d.loc[d['block_type'] == c, 'rt'] for c in CONDS]
        print(f"{lab}: median RT regular {r.median():.3f} vs irregular {i.median():.3f} s "
              f"(Mann-Whitney p = {mannwhitneyu(r, i).pvalue:.2g}); QA {QA[key]}")
    beh, fits = pd.DataFrame(beh), pd.DataFrame(fits)
    if len(fits):
        base = fits[fits['model'] == 'base'].set_index(['subject', 'condition'])[['AIC', 'BIC']]
        fits = fits.join(base, on=['subject', 'condition'], rsuffix='_base')
        fits['dAIC'], fits['dBIC'] = fits['AIC'] - fits['AIC_base'], fits['BIC'] - fits['BIC_base']
        fits = fits.drop(columns=['AIC_base', 'BIC_base'])
    return beh, fits

