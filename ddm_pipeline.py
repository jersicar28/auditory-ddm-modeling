class DriftCoherence(pm.Drift):
    name = 'DriftCoherence'
    required_parameters = ['v_coh']
    required_conditions = ['signed_coherence']
    def get_drift(self, conditions, **kwargs):
        return self.v_coh * conditions['signed_coherence']

def build_model(name):          # 'base' or 'bias' (bias adds a starting point, fraction of bound)
    kw = dict(drift=DriftCoherence(v_coh=Fittable(minval=0, maxval=20)),
              noise=NoiseConstant(noise=1),
              bound=BoundCollapsingLinear(B=Fittable(minval=0.1, maxval=3.0),
                                          t=Fittable(minval=0, maxval=2.0)),
              overlay=OverlayChain(overlays=[
                  OverlayNonDecision(nondectime=Fittable(minval=0, maxval=0.5)),
                  OverlayUniformMixture(umixturecoef=Fittable(minval=0, maxval=0.1))]),
              dx=DX, dt=DT, T_dur=T_DUR, choice_names=('high', 'low'))
    if name == 'bias':
        kw['IC'] = ICPointRatio(x0=Fittable(minval=-0.9, maxval=0.9))
    return Model(name=name, **kw)

def to_sample(df):
    return pyddm.Sample.from_pandas_dataframe(
        df[['rt', 'choice_int', 'signed_coherence']], rt_column_name='rt',
        choice_column_name='choice_int', choice_names=('high', 'low'))

TAG = '_real' if USE_REALIZED else ''
def fit_path(key, cond, model):
    return f'{MODEL_DIR}fit_{key}_{cond}_{model}{TAG}.pkl'

def load_fit(key, cond, model):
    p = fit_path(key, cond, model)
    if not os.path.exists(p):
        return None
    with open(p, 'rb') as f:
        return pickle.load(f)

def nll_of(fit):
    try:
        return float(fit.fitresult.value())
    except Exception:
        return float(fit.fitresult.val)

def fit_stats(fit, n_fallback=np.nan):
    props = getattr(fit.fitresult, 'properties', {}) or {}
    k = props.get('nparams', len(fit.get_model_parameters()))
    n = props.get('samplesize', n_fallback)
    nll = nll_of(fit)
    return dict(n=int(n), k=int(k), logL=-nll, AIC=2 * k + 2 * nll, BIC=k * np.log(n) + 2 * nll)

def params_of(fit):
    """Fitted parameters + names of any sitting at a bound (lapse: only the upper bound counts)."""
    out, pinned = {}, []
    for dct in fit.parameters().values():
        for name, v in dct.items():
            if hasattr(v, 'minval'):
                x, lo, hi = float(v), v.minval, v.maxval
                out[name] = x
                tol = 0.02 * (hi - lo)
                if (hi - x < tol) or (name != 'umixturecoef' and x - lo < tol):
                    pinned.append(name)
    return out, ','.join(pinned)

def fit_all(key, models=MODELS, conds=CONDS, overwrite=False):
    """Fit every cond x model for one subject. Resumable: existing pickles are skipped."""
    d = data_for(key)
    for cond in conds:
        sample = to_sample(d[d['block_type'] == cond])
        for m in models:
            p = fit_path(key, cond, m)
            if os.path.exists(p) and not overwrite:
                print('skip (exists):', os.path.basename(p)); continue
            print(f'Fitting {key} / {cond} / {m} ({len(sample)} trials) ...')
            fitted = fit_adjust_model(sample, build_model(m), **FIT_KW)
            with open(p + '.tmp', 'wb') as f:                       # save immediately, atomically
                pickle.dump(fitted, f)
            os.replace(p + '.tmp', p)
            s = fit_stats(fitted, len(sample))
            print(f"  saved {os.path.basename(p)} | logL={s['logL']:.2f} AIC={s['AIC']:.2f} BIC={s['BIC']:.2f}")

