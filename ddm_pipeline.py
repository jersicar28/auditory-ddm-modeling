import pyddm, pyddm.models as pm
from pyddm import Model, Fittable, fit_adjust_model
from pyddm.models import (NoiseConstant, BoundCollapsingLinear, OverlayChain,
                          OverlayNonDecision, OverlayUniformMixture, ICPointRatio)

def realized(c):                # coherence actually produced with N_BURSTS integer bursts
    return (2 * round((c + 1) / 2 * N_BURSTS) - N_BURSTS) / N_BURSTS

QA, _DATA = {}, {}
def data_for(key):
    """Load + clean one subject (cached). Exclusions: timeouts and RT <= MIN_RT."""
    if key in _DATA:
        return _DATA[key]
    folder = DATA_ROOT + SUBJECTS[key]['folder']
    files = sorted(glob.glob(folder + '/*.csv'))
    if not files:
        raise FileNotFoundError(f'No CSVs in {folder}')
    raw = pd.concat([pd.read_csv(f).assign(source_file=os.path.basename(f)) for f in files],
                    ignore_index=True)
    timeout = raw['response'].eq('none')
    fast = ~timeout & raw['rt'].le(MIN_RT)
    d = raw[~timeout & ~fast].copy()
    d['choice_int'] = (d['response'] == 'high').astype(int)        # 1 = high = upper bound
    d['realized_coh'] = d['coherence'].map(realized)
    d['signed_coherence'] = d['realized_coh'] if USE_REALIZED else d['coherence']
    QA[key] = dict(files=len(files), raw=len(raw), timeouts=int(timeout.sum()), too_fast=int(fast.sum()))
    _DATA[key] = d
    return d

