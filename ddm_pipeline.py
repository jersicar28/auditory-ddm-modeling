# [6] Fit quality: observed vs model-predicted choices and RTs
def predict(fit, df):
    """Model predictions from each fit's own solution, weighted by trials run at each coherence."""
    t, dt = np.asarray(fit.t_domain()), fit.dt
    w = df['signed_coherence'].value_counts(normalize=True)
    per_coh, pdf = {}, {'high': np.zeros_like(t), 'low': np.zeros_like(t)}
    for c in sorted(w.index):
        sol = fit.solve(conditions={'signed_coherence': float(c)})
        ph, pl = np.asarray(sol.pdf('high')), np.asarray(sol.pdf('low'))
        pdec = (ph.sum() + pl.sum()) * dt
        per_coh[c] = dict(p_high=ph.sum() * dt / pdec, mean_rt=(t * (ph + pl)).sum() * dt / pdec)
        pdf['high'] += w[c] * ph; pdf['low'] += w[c] * pl
    return t, dt, per_coh, pdf

def fit_quality(key, models=MODELS, qs=(.1, .3, .5, .7, .9), show=True):
    d, lab = data_for(key), SUBJECTS[key]['label']
    rows, summ = [], []
    for m in models:
        fig, axes = plt.subplots(2, 3, figsize=(14, 7))
        for r, cond in enumerate(CONDS):
            fit = load_fit(key, cond, m)
            if fit is None:
                print('missing fit:', key, cond, m); continue
            df = d[d['block_type'] == cond]
            t, dt, per_coh, pdf = predict(fit, df)
            cohs = np.array(sorted(per_coh))
            g = df.groupby('signed_coherence')
            op = g['choice_int'].mean().reindex(cohs); ose = np.sqrt(op * (1 - op) / g.size().reindex(cohs))
            pp = np.array([per_coh[c]['p_high'] for c in cohs])
            ort, orse = g['rt'].mean().reindex(cohs), g['rt'].sem().reindex(cohs)
            prt = np.array([per_coh[c]['mean_rt'] for c in cohs])
            ax = axes[r, 0]; ax.errorbar(cohs, op, ose, fmt='o', ms=4, capsize=2, color=COL[cond]); ax.plot(cohs, pp, 'k-')
            ax.set(title=f'{cond}: P(high)', xlabel='Signed coherence')
            ax = axes[r, 1]; ax.errorbar(cohs, ort, orse, fmt='o', ms=4, capsize=2, color=COL[cond]); ax.plot(cohs, prt, 'k-')
            ax.set(title=f'{cond}: mean RT (s)', xlabel='Signed coherence')
            ax = axes[r, 2]
            ax.hist(df['rt'], bins=np.arange(0, 2.5, .05), density=True, color=COL[cond], alpha=.4, label='observed')
            pall = pdf['high'] + pdf['low']; ax.plot(t, pall / (pall.sum() * dt), 'k-', label='model')
            ax.set(title=f'{cond}: RT distribution', xlabel='RT (s)', xlim=(0, 2.5)); ax.legend(frameon=False, fontsize=8)
            errs = []
            for ch in ('high', 'low'):
                obs = df.loc[df['choice_int'] == (ch == 'high'), 'rt']
                if len(obs) < 10: continue
                cdf = np.cumsum(pdf[ch]); cdf /= cdf[-1]
                for q, o, p_ in zip(qs, np.quantile(obs, qs), np.interp(qs, cdf, t)):
                    rows.append(dict(subject=lab, model=m, condition=cond, choice=ch, quantile=q,
                                     obs_rt=o, pred_rt=p_, diff=p_ - o)); errs.append(abs(p_ - o))
            summ.append(dict(subject=lab, model=m, condition=cond,
                             rmse_p_high=np.sqrt(np.mean((op.values - pp) ** 2)),
                             rmse_mean_rt=np.sqrt(np.mean((ort.values - prt) ** 2)),
                             mean_abs_quantile_err=np.mean(errs) if errs else np.nan))
        fig.suptitle(f'{lab}, {m} model: observed (points/bars) vs predicted (black)')
        fig.tight_layout()
        fig.savefig(f'{FIG_DIR}fig_fitquality_{key}_{m}{TAG}.png', dpi=300, bbox_inches='tight')
        plt.show() if show else plt.close(fig)
    q, s = pd.DataFrame(rows), pd.DataFrame(summ)
    q.to_csv(f'{FIG_DIR}fit_quality_quantiles_{key}{TAG}.csv', index=False)
    return s, q

for k in ACTIVE:
    s, q = fit_quality(k)
    print(s.round(3).to_string(index=False))

